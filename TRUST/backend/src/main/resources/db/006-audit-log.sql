  id INTEGER PRIMARY KEY CHECK(id=1), archive_paused BOOLEAN NOT NULL DEFAULT FALSE,
  chain_paused BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
