import router from './router'
import { ElMessage } from 'element-plus'
import NProgress from 'nprogress'
import 'nprogress/nprogress.css'
import { getToken, hasNativeSession, setNativeSession } from '@/utils/auth'
import { isHttp, isPathMatch } from '@/utils/validate'
import { isRelogin } from '@/utils/request'
import useUserStore from '@/store/modules/user'
import useSettingsStore from '@/store/modules/settings'
import usePermissionStore from '@/store/modules/permission'
import { centralAction, firstAuthorizedPage } from '@/utils/central-authorization'

NProgress.configure({ showSpinner: false })

const whiteList = ['/login', '/register']

const isWhiteList = (path) => {
  return whiteList.some(pattern => isPathMatch(pattern, path))
}

router.beforeEach(async (to, from, next) => {
  NProgress.start()
  if (!getToken() && !hasNativeSession()) {
    try {
      await useUserStore().getInfo()
      setNativeSession(true)
      // The existing branch below installs the authorized dynamic route table.
      useUserStore().roles = []
    } catch { /* A native emergency login remains available when no SSO session exists. */ }
  }
  if (getToken() || hasNativeSession()) {
    to.meta.title && useSettingsStore().setTitle(to.meta.title)
    /* has token*/
    if (to.path === '/login') {
      next({ path: '/' })
      NProgress.done()
    } else if (isWhiteList(to.path)) {
      next()
    } else {
      if (useUserStore().roles.length === 0) {
        isRelogin.show = true
        // 判断当前用户是否已拉取完user_info信息
        useUserStore().getInfo().then(() => {
          isRelogin.show = false
          return usePermissionStore().generateRoutes().then(accessRoutes => {
            // 根据roles权限生成可访问的路由表
            accessRoutes.forEach(route => {
              if (!isHttp(route.path)) {
                router.addRoute(route) // 动态添加可访问路由表
              }
            })
            next({ ...to, replace: true }) // hack方法 确保addRoutes已完成
          })
        }).catch(err => {
          useUserStore().logOut().then(() => {
            ElMessage.error(err)
            next({ path: '/' })
          })
        })
      } else {
        const authorization = useUserStore().centralAuthorization
        if (authorization?.version === 2 && !['/401', '/login'].includes(to.path)) {
          if (['/', '/index'].includes(to.path)) {
            next({ path: firstAuthorizedPage(usePermissionStore().addRoutes, authorization), replace: true })
            return
          }
          if (!to.matched.some(route => centralAction(authorization, route.meta.stableMenuKey, 'VIEW'))) {
            next({ path: '/401', replace: true })
            return
          }
        }
        next()
      }
    }
  } else {
    // 没有token
    if (isWhiteList(to.path)) {
      // 在免登录白名单，直接进入
      next()
    } else {
      next(`/login?redirect=${to.fullPath}`) // 否则全部重定向到登录页
      NProgress.done()
    }
  }
})

router.afterEach(() => {
  NProgress.done()
})
